import { describe, expect, test } from "bun:test";
import {
  dataFormatFirstLine,
  dataFormatText,
  exampleOf,
  type DataFormatUse,
} from "../../../../src/core/widgets/data-format-file.ts";
import { mergeFormats } from "../../../../src/core/widgets/data-formats.ts";

const habitsSchema = {
  type: "object",
  required: ["name", "checks"],
  properties: {
    name: { type: "string", description: "The habit | name." },
    kind: { enum: ["yesNo", "number"] },
    frequency: { type: "object", properties: { times: { type: "integer" } } },
    checks: {
      type: "array",
      items: {
        type: "object",
        required: ["date"],
        properties: { date: { type: "string", format: "date" }, value: { type: "number" } },
      },
    },
    tags: { type: "array", items: { type: "string" } },
  },
};

const habits: DataFormatUse = {
  widget: "example-owner/habits",
  name: "Habits",
  access: "write",
  files: "*.json",
  single: false,
  schema: habitsSchema,
};

describe("dataFormatText", () => {
  test("starts with the generated line, and lists the widgets, the rules and each field", () => {
    const text = dataFormatText("Life/Habits", [habits]);
    expect(text.split("\n")[0]).toBe(dataFormatFirstLine);
    expect(dataFormatFirstLine).toBe(
      "Generated by Eva. Do not edit. Write your notes in the AGENTS.md or the README.md of this folder.",
    );
    expect(text).toContain("# The data format of `Life/Habits`");
    expect(text).toContain(
      "- Habits (`example-owner/habits`) reads and writes the files `*.json` in this folder and its subfolders.",
    );
    expect(text).toContain("Write every required field.");
    expect(text).toContain("| `name` | string | any | Habits | Habits | The habit \\| name. |");
    expect(text).toContain('| `kind` | any | "yesNo", "number" |  | Habits |  |');
    expect(text).toContain("| `checks[].date` | string | format date | Habits | Habits |  |");
    expect(text).toContain("```json\n");
  });

  test("names the widget of each field of a shared folder", () => {
    const training: DataFormatUse = {
      widget: "example-owner/training",
      name: "Training",
      access: "read",
      files: null,
      single: false,
      schema: {
        type: "object",
        required: ["place"],
        properties: { name: { type: "string" }, place: { type: "string" } },
      },
    };
    const text = dataFormatText("Life/Habits", [habits, training]);
    expect(text).toContain("- Training (`example-owner/training`) reads every file in this folder and its subfolders.");
    expect(text).toContain("| `name` | string | any | Habits | Habits, Training | The habit \\| name. |");
    expect(text).toContain("| `place` | string | any | Training | Training |  |");
  });

  test("describes the one file of a file input", () => {
    const text = dataFormatText("Life", [{ ...habits, files: "goals.yaml", single: true }]);
    expect(text).toContain("- Habits (`example-owner/habits`) reads and writes the file `goals.yaml`.");
  });

  test("is the same text for the same widgets", () => {
    expect(dataFormatText("Life/Habits", [habits])).toBe(dataFormatText("Life/Habits", [habits]));
  });
});

describe("exampleOf", () => {
  test("builds one file with a value for each field", () => {
    expect(exampleOf(mergeFormats([{ widget: "a", name: "a", schema: habitsSchema }]).fields)).toEqual({
      name: "text",
      kind: "yesNo",
      frequency: { times: 1 },
      checks: [{ date: "2026-01-01", value: 1 }],
      tags: ["text"],
    });
  });

  test("gives a nullable field a real value", () => {
    const schema = { type: "object", properties: { note: { type: ["string", "null"] } } };
    expect(exampleOf(mergeFormats([{ widget: "a", name: "a", schema }]).fields)).toEqual({ note: "text" });
  });

  test("gives a value for each common format and type", () => {
    const schema = {
      type: "object",
      properties: {
        startAt: { type: "string", format: "date-time" },
        done: { type: "boolean" },
        nothing: { type: "null" },
        fixed: { const: 3 },
        free: {},
        open: { type: "object" },
        list: { type: "array" },
      },
    };
    expect(exampleOf(mergeFormats([{ widget: "a", name: "a", schema }]).fields)).toEqual({
      startAt: "2026-01-01T09:30:00Z",
      done: true,
      nothing: null,
      fixed: 3,
      free: "text",
      open: {},
      list: [],
    });
  });
});
